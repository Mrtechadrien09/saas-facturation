interface LanguageContextValue {
  language: Language;
  setLanguage: (language: Language) => void;
  t: (message: string) => string;
}

const LanguageContext = createContext<LanguageContextValue | null>(null);

export function LanguageProvider({ children }: { children: React.ReactNode }) {
  const [language, setLanguageState] = useState<Language>("fr");

  useEffect(() => {
    document.documentElement.lang = language;
    document.title = language === "en"
      ? "Simplifact | Business invoicing software"
      : "Simplifact | SaaS de facturation pour entreprises";
    const description = document.querySelector('meta[name="description"]');
    if (description) {
      description.setAttribute(
        "content",
        language === "en"
          ? "Invoicing and business management software for SMEs, mid-sized companies, and B2B teams."
          : "Solution de facturation et de gestion commerciale pour PME, ETI et services B2B."
      );
    }
  }, [language]);

  useEffect(() => {
    const savedLanguage = window.localStorage.getItem(STORAGE_KEY);
    if (savedLanguage === "en" || savedLanguage === "fr") {
      setLanguageState(savedLanguage);
      document.documentElement.lang = savedLanguage;
    }
  }, []);

  const setLanguage = (nextLanguage: Language) => {
    window.localStorage.setItem(STORAGE_KEY, nextLanguage);
    document.documentElement.lang = nextLanguage;
    setLanguageState(nextLanguage);
  };

  const t = (message: string) => language === "en" ? englishMessages[message] || message : message;

  return (
    <LanguageContext.Provider value={{ language, setLanguage, t }}>
      {children}
    </LanguageContext.Provider>
  );
}

export function useLanguage() {
  const context = useContext(LanguageContext);
  if (!context) throw new Error("useLanguage must be used within LanguageProvider");
  return context;
}